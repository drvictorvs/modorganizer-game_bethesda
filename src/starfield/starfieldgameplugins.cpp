#include "starfieldgameplugins.h"
#include <iplugingame.h>
#include <ipluginlist.h>
#include <iprofile.h>

#include <QDir>
#include <QFile>
#include <QFileInfo>
#include <QSet>

using namespace MOBase;

StarfieldGamePlugins::StarfieldGamePlugins(MOBase::IOrganizer* organizer)
    : CreationGamePlugins(organizer)
{}

bool StarfieldGamePlugins::mediumPluginsAreSupported()
{
  return true;
}

void StarfieldGamePlugins::writePluginList(const IPluginList* pluginList,
                                           const QString& filePath)
{
  if (m_Organizer->managedGame()->loadOrderMechanism() ==
      MOBase::IPluginGame::LoadOrderMechanism::PluginsTxt) {
    CreationGamePlugins::writePluginList(pluginList, filePath);
  }
}

QStringList StarfieldGamePlugins::readPluginList(MOBase::IPluginList* pluginList)
{
  if (m_Organizer->managedGame()->loadOrderMechanism() ==
      MOBase::IPluginGame::LoadOrderMechanism::PluginsTxt) {
    // Check the header before parsing: MO2 rewrites the file with its own header
    // right after this refresh.
    const bool rewrittenExternally = pluginsTxtRewrittenExternally();

    QStringList loadOrder = CreationGamePlugins::readPluginList(pluginList);

    if (rewrittenExternally &&
        m_Organizer
            ->pluginSetting(m_Organizer->managedGame()->name(),
                            "reenable_vanilla_plugins")
            .toBool()) {
      reactivateVanillaPlugins(pluginList);
    }

    return loadOrder;
  }
  return {};
}

bool StarfieldGamePlugins::pluginsTxtRewrittenExternally() const
{
  QFile file(m_Organizer->profile()->absolutePath() + "/plugins.txt");
  if (!file.open(QIODevice::ReadOnly) || file.size() == 0) {
    // missing or empty: MO2 always writes at least its header
    return true;
  }

  // MO2 always starts the file with this line (CreationGamePlugins::writePluginList);
  // Starfield writes "# This file is used by Starfield to keep track of your
  // downloaded content." instead.
  const QByteArray firstLine = file.readLine().trimmed();
  return !firstLine.startsWith(
      "# This file was automatically generated by Mod Organizer.");
}

void StarfieldGamePlugins::reactivateVanillaPlugins(IPluginList* pluginList) const
{
  const IPluginGame* game = m_Organizer->managedGame();
  const QDir vanillaData(game->gameDirectory().absoluteFilePath("Data"));
  const QStringList pluginNames = pluginList->pluginNames();

  QStringList reactivated;
  for (const QString& pluginName : pluginNames) {
    if (pluginList->state(pluginName) != IPluginList::STATE_INACTIVE) {
      continue;
    }

    if (pluginName.startsWith("BlueprintShips-", Qt::CaseInsensitive)) {
      continue;
    }

    if (QFileInfo::exists(vanillaData.absoluteFilePath(pluginName))) {
      pluginList->setState(pluginName, IPluginList::STATE_ACTIVE);
      reactivated.append(pluginName);
    }
  }

  QSet<QString> activePlugins;
  for (const QString& pluginName : pluginNames) {
    if (pluginList->state(pluginName) == IPluginList::STATE_ACTIVE) {
      activePlugins.insert(pluginName.toCaseFolded());
    }
  }

  const QString blueprintShipsPrefix = "BlueprintShips-";
  for (const QString& pluginName : pluginNames) {
    if (pluginList->state(pluginName) != IPluginList::STATE_INACTIVE ||
        !pluginName.startsWith(blueprintShipsPrefix, Qt::CaseInsensitive)) {
      continue;
    }

    const QString mainPlugin =
        pluginName.mid(blueprintShipsPrefix.size()).trimmed().toCaseFolded();
    if (!mainPlugin.isEmpty() && activePlugins.contains(mainPlugin)) {
      // Re-enable a ship-blueprint sidecar only when its main plugin is active.
      pluginList->setState(pluginName, IPluginList::STATE_ACTIVE);
      reactivated.append(pluginName);
    }
  }

  if (!reactivated.isEmpty()) {
    qInfo("plugins.txt was rewritten outside Mod Organizer; re-enabled vanilla "
          "and paired BlueprintShips plugins: %s",
          qUtf8Printable(reactivated.join(", ")));
  }
}
